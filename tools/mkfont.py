#!/usr/bin/env python3
"""Builds kernel/font.inc from tools/font5x7.txt and kernel/fontp.inc from
tools/fontp9.txt and tools/fontp12.txt (original code).

  tools/mkfont.py          write kernel/font.inc and kernel/fontp.inc
  tools/mkfont.py --check  exit 1 if either is out of date

Each 5 x 7 glyph becomes seven bytes, one per row, top first; bit 4 is the
leftmost column. The table covers codes 0x20 to 0x7E with no gaps.

The proportional faces (2.2-propfont) are up to eight pixels wide: each
glyph is a width byte (in the face's width table) and one byte per row,
bit 7 the leftmost column.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'tools', 'font5x7.txt')
OUT = os.path.join(ROOT, 'kernel', 'font.inc')
OUTP = os.path.join(ROOT, 'kernel', 'fontp.inc')
FACES = [('FONT_9', 'fontp9', 9), ('FONT_12', 'fontp12', 12)]
FIRST, LAST = 0x20, 0x7E


def read():
    glyphs = {}
    with open(SRC, encoding='ascii') as f:
        for n, line in enumerate(f, 1):
            line = line.strip()
            if not line or line.startswith('#'):
                continue
            code, *rows = line.split()
            code = int(code, 16)
            if len(rows) != 7 or any(len(r) != 5 or set(r) - set('#.') for r in rows):
                sys.exit('font5x7.txt:%d: need seven rows of five # or .' % n)
            if code in glyphs:
                sys.exit('font5x7.txt:%d: %02x twice' % (n, code))
            glyphs[code] = [int(r.replace('#', '1').replace('.', '0'), 2) for r in rows]
    missing = [c for c in range(FIRST, LAST + 1) if c not in glyphs]
    if missing:
        sys.exit('font5x7.txt: no glyph for %s' % ', '.join('%02x' % c for c in missing))
    return glyphs


def render(glyphs):
    out = ['; Generated by tools/mkfont.py from tools/font5x7.txt. Do not edit.',
           'FONT_FIRST equ 0x%02X' % FIRST,
           'FONT_LAST  equ 0x%02X' % LAST,
           'FONT_W     equ 5',
           'FONT_H     equ 7',
           'font5x7:']
    for c in range(FIRST, LAST + 1):
        rows = ', '.join('0x%02X' % b for b in glyphs[c])
        name = repr(chr(c)) if c != 0x27 else '"\'"'
        out.append('    db %s   ; %02x %s' % (rows, c, name))
    return '\n'.join(out) + '\n'


def read_p(name, height):
    """-> {code: [row strings]} of tools/<name>.txt, a proportional face."""
    path = os.path.join(ROOT, 'tools', name + '.txt')
    glyphs = {}
    with open(path, encoding='ascii') as f:
        for n, line in enumerate(f, 1):
            line = line.strip()
            if not line or line.startswith('#'):
                continue
            code, *rows = line.split()
            code = int(code, 16)
            if len(rows) != height or len(set(map(len, rows))) != 1 or \
                    not 1 <= len(rows[0]) <= 8 or any(set(r) - set('#.') for r in rows):
                sys.exit('%s.txt:%d: need %d rows of one to eight # or .' % (name, n, height))
            if code in glyphs:
                sys.exit('%s.txt:%d: %02x twice' % (name, n, code))
            glyphs[code] = rows
    missing = [c for c in range(FIRST, LAST + 1) if c not in glyphs]
    if missing:
        sys.exit('%s.txt: no glyph for %s' % (name, ', '.join('%02x' % c for c in missing)))
    return glyphs


def render_p():
    out = ['; Generated by tools/mkfont.py from tools/fontp9.txt and tools/fontp12.txt.',
           '; Do not edit.']
    for n, (const, _, _) in enumerate(FACES):
        out.append('%-8s equ %d' % (const, n))
    out.append('FONTP_FACES equ %d' % len(FACES))
    out.append('fontp_faces:                ; per face: widths, bitmaps, height')
    for _, name, height in FACES:
        out.append('    dd %s_w, %s_bits, %d' % (name, name, height))
    for _, name, height in FACES:
        glyphs = read_p(name, height)
        out.append('%s_w:' % name)
        for c in range(FIRST, LAST + 1, 16):
            out.append('    db ' + ', '.join(str(len(glyphs[k][0])) for k in range(c, min(c + 16, LAST + 1))))
        out.append('%s_bits:' % name)
        for c in range(FIRST, LAST + 1):
            rows = ', '.join('0x%02X' % (int(r.replace('#', '1').replace('.', '0').ljust(8, '0'), 2))
                             for r in glyphs[c])
            out.append('    db %s   ; %02x' % (rows, c))
    return '\n'.join(out) + '\n'


def main():
    for path, text in ((OUT, render(read())), (OUTP, render_p())):
        if sys.argv[1:] == ['--check']:
            try:
                with open(path, encoding='ascii') as f:
                    current = f.read()
            except FileNotFoundError:
                current = None
            if current != text:
                sys.exit('%s is out of date: run tools/mkfont.py' % os.path.relpath(path, ROOT))
            continue
        with open(path, 'w', encoding='ascii') as f:
            f.write(text)


if __name__ == '__main__':
    main()
