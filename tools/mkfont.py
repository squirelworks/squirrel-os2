#!/usr/bin/env python3
"""Builds kernel/font.inc from tools/font5x7.txt (original code).

  tools/mkfont.py          write kernel/font.inc
  tools/mkfont.py --check  exit 1 if kernel/font.inc is out of date

Each glyph becomes seven bytes, one per row, top first; bit 4 is the
leftmost column. The table covers codes 0x20 to 0x7E with no gaps.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'tools', 'font5x7.txt')
OUT = os.path.join(ROOT, 'kernel', 'font.inc')
FIRST, LAST = 0x20, 0x7E


def read():
    glyphs = {}
    with open(SRC, encoding='ascii') as f:
        for n, line in enumerate(f, 1):
            line = line.strip()
            if not line or line.startswith('#'):
                continue
            code, *rows = line.split()
            code = int(code, 16)
            if len(rows) != 7 or any(len(r) != 5 or set(r) - set('#.') for r in rows):
                sys.exit('font5x7.txt:%d: need seven rows of five # or .' % n)
            if code in glyphs:
                sys.exit('font5x7.txt:%d: %02x twice' % (n, code))
            glyphs[code] = [int(r.replace('#', '1').replace('.', '0'), 2) for r in rows]
    missing = [c for c in range(FIRST, LAST + 1) if c not in glyphs]
    if missing:
        sys.exit('font5x7.txt: no glyph for %s' % ', '.join('%02x' % c for c in missing))
    return glyphs


def render(glyphs):
    out = ['; Generated by tools/mkfont.py from tools/font5x7.txt. Do not edit.',
           'FONT_FIRST equ 0x%02X' % FIRST,
           'FONT_LAST  equ 0x%02X' % LAST,
           'FONT_W     equ 5',
           'FONT_H     equ 7',
           'font5x7:']
    for c in range(FIRST, LAST + 1):
        rows = ', '.join('0x%02X' % b for b in glyphs[c])
        name = repr(chr(c)) if c != 0x27 else '"\'"'
        out.append('    db %s   ; %02x %s' % (rows, c, name))
    return '\n'.join(out) + '\n'


def main():
    text = render(read())
    if sys.argv[1:] == ['--check']:
        try:
            with open(OUT, encoding='ascii') as f:
                current = f.read()
        except FileNotFoundError:
            current = None
        if current != text:
            sys.exit('kernel/font.inc is out of date: run tools/mkfont.py')
        return
    with open(OUT, 'w', encoding='ascii') as f:
        f.write(text)


if __name__ == '__main__':
    main()
