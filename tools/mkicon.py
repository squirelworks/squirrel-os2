#!/usr/bin/env python3
"""Icons from text art (2.3-icons, original code).

  tools/mkicon.py               write kernel/icons.inc from tools/icons/*.txt
  tools/mkicon.py --check       exit 1 if kernel/icons.inc is out of date
  tools/mkicon.py ART.txt FILE  write one icon file (for a disk)

Art: "colour X n" lines name up to 15 letters (n = a palette index), then
32 rows of 32 characters: a named letter, or "." for transparent. Lines
starting with "#" are comments.

Icon file (SQIC), 536 bytes:
  0  'SQIC'
  4  width (32), height (32), flags (0), reserved (0)
  8  16 bytes: the palette index of each nibble value; nibble 0 is
     transparent, so byte 8 is unused
  24 width * height / 2 bytes, rows top first, two pixels a byte, the
     left one in the high nibble
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(ROOT, 'tools', 'icons')
OUT = os.path.join(ROOT, 'kernel', 'icons.inc')
W = H = 32


def read(path):
    """-> bytes of the icon described by the art file at path"""
    colours, rows = {}, []
    name = os.path.basename(path)
    with open(path, encoding='ascii') as f:
        for n, line in enumerate(f, 1):
            line = line.rstrip('\n')
            if not line.strip() or line.startswith('#'):
                continue
            if line.startswith('colour '):
                parts = line.split('#')[0].split()
                if len(parts) != 3 or len(parts[1]) != 1 or parts[1] == '.':
                    sys.exit('%s:%d: need "colour X n"' % (name, n))
                if len(colours) == 15:
                    sys.exit('%s:%d: more than 15 colours' % (name, n))
                colours[parts[1]] = (len(colours) + 1, int(parts[2], 0) & 0xFF)
                continue
            if len(line) != W or any(c != '.' and c not in colours for c in line):
                sys.exit('%s:%d: need %d characters, each "." or a named colour' % (name, n, W))
            rows.append(line)
    if len(rows) != H:
        sys.exit('%s: need %d rows, found %d' % (name, H, len(rows)))
    cmap = [0] * 16
    for nib, index in colours.values():
        cmap[nib] = index
    data = bytearray(b'SQIC' + bytes([W, H, 0, 0]) + bytes(cmap))
    for row in rows:
        nibs = [0 if c == '.' else colours[c][0] for c in row]
        data += bytes((nibs[i] << 4) | nibs[i + 1] for i in range(0, W, 2))
    return bytes(data)


def render():
    names = sorted(f[:-4] for f in os.listdir(ART) if f.endswith('.txt'))
    out = ['; Generated by tools/mkicon.py from tools/icons/*.txt. Do not edit.',
           'ICON_SIZE equ %d' % (24 + W * H // 2),
           'ICON_COUNT equ %d' % len(names)]
    for i, name in enumerate(names):
        out.append('ICON_%s equ %d' % (name.upper(), i))
    out.append('icon_table:                 ; per icon: its name, its data')
    for name in names:
        out.append('    dd icon_n_%s, icon_%s' % (name, name))
    for name in names:
        data = read(os.path.join(ART, name + '.txt'))
        out.append("icon_n_%s db '%s', 0" % (name, name))
        out.append('icon_%s:' % name)
        for i in range(0, len(data), 16):
            out.append('    db ' + ', '.join('0x%02X' % b for b in data[i:i + 16]))
    return '\n'.join(out) + '\n'


def main():
    args = sys.argv[1:]
    if len(args) == 2:
        with open(args[1], 'wb') as f:
            f.write(read(args[0]))
        return
    text = render()
    if args == ['--check']:
        try:
            with open(OUT, encoding='ascii') as f:
                current = f.read()
        except FileNotFoundError:
            current = None
        if current != text:
            sys.exit('kernel/icons.inc is out of date: run tools/mkicon.py')
        return
    with open(OUT, 'w', encoding='ascii') as f:
        f.write(text)


if __name__ == '__main__':
    main()
