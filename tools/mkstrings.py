#!/usr/bin/env python3
"""Builds kernel/strings.inc from localization/*/strings.txt (original code).

  tools/mkstrings.py          write kernel/strings.inc
  tools/mkstrings.py --check  exit 1 if kernel/strings.inc is out of date

Each strings.txt holds key=value lines (the value runs to the end of the
line, trailing spaces included). English defines the keys; another
language may leave a key out, and the kernel then shows the English text.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOC = os.path.join(ROOT, 'localization')
OUT = os.path.join(ROOT, 'kernel', 'strings.inc')


def read(lang):
    table = {}
    with open(os.path.join(LOC, lang, 'strings.txt'), encoding='utf-8') as f:
        for n, line in enumerate(f, 1):
            line = line.rstrip('\n')
            if not line or line.startswith('#'):
                continue
            key, sep, value = line.partition('=')
            if not sep:
                sys.exit('%s/strings.txt:%d: no "="' % (lang, n))
            table[key] = value
    return table


def asm_string(text):
    data = text.encode('latin-1')    # the VGA font is code page 437; keep to ASCII
    if any(b < 32 or b > 126 for b in data):
        sys.exit('non-ASCII text: %r' % text)
    if not text:
        return '0'
    for q in "'\"":
        if q not in text:
            return '%s%s%s, 0' % (q, text, q)
    return ', '.join(str(b) for b in data) + ', 0'


def generate():
    langs = sorted(d for d in os.listdir(LOC) if os.path.isdir(os.path.join(LOC, d)))
    langs.remove('en')
    langs.insert(0, 'en')               # the fallback comes first
    tables = {l: read(l) for l in langs}
    keys = list(tables['en'])
    for l in langs:
        extra = set(tables[l]) - set(keys)
        if extra:
            sys.exit('%s has keys English lacks: %s' % (l, ', '.join(sorted(extra))))
        if len(l) > 3:
            sys.exit('language code too long: %s' % l)
    out = ['; Generated by tools/mkstrings.py from localization/*/strings.txt.',
           '; Do not edit: change the strings.txt files and run the tool.', '']
    for i, k in enumerate(keys):
        out.append('LS_%s equ %d' % (k.upper(), i))
    out += ['LS_COUNT equ %d' % len(keys), 'LANG_COUNT equ %d' % len(langs), '',
            'align 4',
            'lang_codes:']
    for l in langs:
        out.append("    db '%s'%s" % (l, ', 0' * (4 - len(l))))
    out.append('lang_tables: dd ' + ', '.join('ls_' + l for l in langs))
    for l in langs:
        out.append('ls_%s:' % l)
        for k in keys:
            out.append('    dd %s' % (('ls_%s_%s' % (l, k)) if k in tables[l] else '0'))
    for l in langs:
        for k in keys:
            if k in tables[l]:
                out.append('ls_%s_%s db %s' % (l, k, asm_string(tables[l][k])))
    return '\n'.join(out) + '\n'


def main(argv):
    text = generate()
    if '--check' in argv:
        try:
            with open(OUT) as f:
                same = f.read() == text
        except FileNotFoundError:
            same = False
        if not same:
            sys.exit('kernel/strings.inc is out of date: run tools/mkstrings.py')
        return
    with open(OUT, 'w') as f:
        f.write(text)


if __name__ == '__main__':
    main(sys.argv)
