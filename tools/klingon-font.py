# How each Latin letter is read. Klingon only tells q from Q, so every
# other letter maps both cases to one glyph; letters Klingon lacks borrow
# the nearest sound. Romanized Klingon and plain English both come out.
LATIN = {
    'a': 'a', 'b': 'b', 'c': 'q', 'd': 'D', 'e': 'e', 'f': 'v', 'g': KL_GH,
    'h': 'H', 'i': 'I', 'j': 'j', 'k': 'q', 'l': 'l', 'm': 'm', 'n': 'n',
    'o': 'o', 'p': 'p', 'r': 'r', 's': 'S', 't': 't', 'u': 'u',
    'v': 'v', 'w': 'w', 'x': 'Q', 'y': 'y', 'z': 'S',
}


def parse(art):
    rows = art.strip('\n').split('\n')
    assert len(rows) == 12 and all(len(r) == 7 for r in rows), rows
    cell = [0, 0]
    for r in rows:
        cell.append(int(r.replace('.', '0').replace('#', '1') + '0', 2))
    return cell + [0, 0]


def main():
    glyphs = {ord(d): parse(art) for d, art in DIGITS.items()}
    glyphs[ord("'")] = parse(KLINGON["'"])
    for latin, kl in LATIN.items():
        glyphs[ord(latin)] = glyphs[ord(latin.upper())] = parse(KLINGON[kl])
    glyphs[ord('q')] = parse(KLINGON['q'])
    glyphs[ord('Q')] = parse(KLINGON['Q'])
    for cp in (KL_CH, KL_GH, KL_NG, KL_TLH):
        glyphs[cp] = parse(KLINGON[cp])

    print('; Generated by tools/klingon-font.py; edit that, not this.')
    print('; Entries: code point, then 16 rows. Ends with KLINGON_GLYPHS.')
    print()
    print('KLINGON_GLYPHS equ %d' % len(glyphs))
    print()
    print('klingon_font:')
    for cp in sorted(glyphs):
        print('    db 0x%02X, ' % cp + ', '.join('0x%02X' % b for b in glyphs[cp]))


if __name__ == '__main__':
    main()
